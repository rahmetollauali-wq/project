def train_model(texts=None, labels=None):
    """
    Обучает модель классификации и сохраняет её в файл.
    Если тексты и метки не переданы, использует встроенный датасет.
    Пайплайн: очистка текста -> TF-IDF векторизатор -> Multinomial Naive Bayes.
    """
    if texts is None or labels is None:
        texts, labels = get_training_data()
 
    cleaned_texts = [clean_text(t) for t in texts]
 
    # Создаём ML pipeline
    pipeline = Pipeline([
        ('tfidf', TfidfVectorizer(
            max_features=5000,
            ngram_range=(1, 2),   # учитываем биграммы для лучшего качества
            sublinear_tf=True     # сглаживание TF
        )),
        ('clf', MultinomialNB(alpha=0.5))
    ])
 
    # Обучаем модель
    pipeline.fit(cleaned_texts, labels)
 
    # Проверяем наличие папки models и сохраняем туда файл
    os.makedirs('models', exist_ok=True)
    joblib.dump(pipeline, MODEL_PATH)
    print(f"Модель успешно обучена и сохранена в {MODEL_PATH}")
    print(f"Категории: {CATEGORIES}")
 
def predict_category(text):
    """
    Загружает модель и предсказывает категорию для переданного текста новости.
    Если модель не найдена — обучает её автоматически на встроенных данных.
    """
    if not os.path.exists(MODEL_PATH):
        print("Модель не найдена. Выполняю автоматическое обучение...")
        train_model()
 
    pipeline = joblib.load(MODEL_PATH)
    cleaned = clean_text(text)
    prediction = pipeline.predict([cleaned])
    return prediction[0]
 
